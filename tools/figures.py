def tuple_blend(a, b, t):
    """Mix two hex colours, so the grid tints with whatever paper is set."""
    pa = [int(a.lstrip('#')[i:i+2], 16) for i in (0, 2, 4)]
    pb = [int(b.lstrip('#')[i:i+2], 16) for i in (0, 2, 4)]
    return '#%02X%02X%02X' % tuple(round(x + (y - x) * t) for x, y in zip(pa, pb))


def grid(w, h, minor=32, major=160):
    faint = tuple_blend(PAPER, LINE, 0.55)
    out = ['<rect width="%d" height="%d" fill="%s"/>' % (w, h, PAPER)]
    for x in range(0, w, minor):
        out.append('<line x1="%d" y1="0" x2="%d" y2="%d" stroke="%s"/>' % (x, x, h, faint))
    for y in range(0, h, minor):
        out.append('<line x1="0" y1="%d" x2="%d" y2="%d" stroke="%s"/>' % (y, w, y, faint))
    for x in range(0, w, major):
        out.append('<line x1="%d" y1="0" x2="%d" y2="%d" stroke="%s"/>' % (x, x, h, LINE))
    for y in range(0, h, major):
        out.append('<line x1="0" y1="%d" x2="%d" y2="%d" stroke="%s"/>' % (y, w, y, LINE))
    return '\n'.join(out)


def frame(w, h, m=50):
    o = ['<rect x="%d" y="%d" width="%d" height="%d" fill="none" stroke="%s"/>'
         % (m, m, w - 2 * m, h - 2 * m, LINE_STRONG)]
    t = 22
    for cx, cy, sx, sy in ((m, m, 1, 1), (w - m, m, -1, 1), (m, h - m, 1, -1), (w - m, h - m, -1, -1)):
        o.append('<path d="M%d %d H%d M%d %d V%d" stroke="%s" stroke-width="2.5" fill="none"/>'
                 % (cx, cy, cx + t * sx, cx, cy, cy + t * sy, NAVY))
    return '\n'.join(o)


def ground(box, extra=40, pose=None, bb=None):
    """Ground line aligned to the figure's lowest joint, so feet never float."""
    x0, y0, w, h = box
    if pose and pose in POSES:
        fit, _ = _fitter_from(bb or _bbox(POSES[pose]), box)
        y = max(fit(p)[1] for k, p in POSES[pose].items() if k != 'far')
        y = max(y, max([fit(p)[1] for p in (POSES[pose].get('far') or {}).values()] or [y]))
    else:
        y = y0 + h * 0.90
    return ('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" stroke-width="3"/>'
            % (x0 - extra, y, x0 + w + extra, y, LINE_STRONG))


def arrow(x1, y1, x2, y2, colour=None, w=4, dash=False):
    colour = colour or ACCENT
    d = ' stroke-dasharray="9 7"' if dash else ''
    return ('<defs><marker id="a%d" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="5.5" '
            'markerHeight="5.5" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="%s"/></marker></defs>'
            '<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" stroke-width="%d"%s '
            'marker-end="url(#a%d)" stroke-linecap="round"/>'
            % (abs(hash((x1, y1, x2, y2))) % 99999, colour, x1, y1, x2, y2, colour, w, d,
               abs(hash((x1, y1, x2, y2))) % 99999))


def label(x, y, text, size=21, colour=None, weight=600, anchor='start', mono=False):
    colour = colour or NAVY
    fam = ("'IBM Plex Mono','DejaVu Sans Mono',monospace" if mono
           else "'Instrument Sans','Archivo','DejaVu Sans',system-ui,sans-serif")
    return ('<text x="%.0f" y="%.0f" font-family="%s" font-size="%d" font-weight="%d" '
            'fill="%s" text-anchor="%s">%s</text>' % (x, y, fam, size, weight, colour, anchor,
                                                      esc(text)))


def eyebrow(x, y, text):
    return ('<rect x="%.0f" y="%.0f" width="12" height="12" fill="%s"/>' % (x, y - 11, ACCENT)
            + label(x + 22, y, text.upper(), size=17, colour=NAVY, weight=700, mono=True))


def esc(s):
    return (s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;'))


def svg(w, h, body):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">'
            '%s</svg>' % (w, h, w, h, body))


# Poses that hang from or press on apparatus rather than standing on the floor.
HANGING = {'hang': 'bar', 'pullup': 'bar', 'row': 'bar', 'dip': 'bars'}


def support(box, pose, bb=None, extra=40):
    """Draw the apparatus a pose actually uses.

    A hanging pose given a ground line at its feet reads as someone standing
    with an arm raised, which is why this exists.
    """
    kind = HANGING.get(pose)
    if not kind:
        return ground(box, extra, pose, bb)
    fit, k = _fitter_from(bb or _bbox(POSES[pose]), box)
    wx, wy = fit(POSES[pose]['wrist'])
    x0, y0, w, h = box
    if kind == 'bar':
        return ('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" '
                'stroke-width="7" stroke-linecap="round"/>'
                % (x0 - extra * 0.4, wy, x0 + w + extra * 0.4, wy, LINE_STRONG))
    span = w * 0.20
    return ''.join(
        '<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" stroke-width="7" '
        'stroke-linecap="round"/>' % (wx + sx * span * 0.25, wy, wx + sx * span, wy, LINE_STRONG)
        for sx in (-1, 1))
