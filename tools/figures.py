LIMBS = [('neck', 'hip'), ('shoulder', 'elbow'), ('elbow', 'wrist'),
         ('hip', 'knee'), ('knee', 'ankle'), ('ankle', 'toe')]


def _bbox(pose):
    pts = [v for k, v in pose.items() if k != 'far']
    pts += list((pose.get('far') or {}).values())
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def _fitter_from(bb, box, pad=0.10):
    """Build a transform from an explicit bounding box — lets two poses share one
    scale and one ground line, so a start/finish pair is actually comparable."""
    x0, y0, w, h = box
    px, py = w * pad, h * pad
    ax, ay, bx, by = bb
    sw, sh = max(bx - ax, 1e-6), max(by - ay, 1e-6)
    k = min((w - 2 * px) / sw, (h - 2 * py) / sh)
    ox = x0 + (w - sw * k) / 2.0 - ax * k
    oy = y0 + (h - sh * k) / 2.0 - ay * k
    return (lambda p: (ox + p[0] * k, oy + p[1] * k)), k


def union_bbox(names):
    bs = [_bbox(POSES[n]) for n in names]
    return (min(b[0] for b in bs), min(b[1] for b in bs),
            max(b[2] for b in bs), max(b[3] for b in bs))


def _fitter(pose, box, pad=0.10):
    """Scale a pose to fill `box`, preserving aspect, so every figure reads at
    the same visual weight regardless of how tall or wide its pose happens to be."""
    x0, y0, w, h = box
    px, py = w * pad, h * pad
    ax, ay, bx, by = _bbox(pose)
    sw, sh = max(bx - ax, 1e-6), max(by - ay, 1e-6)
    k = min((w - 2 * px) / sw, (h - 2 * py) / sh)
    ox = x0 + (w - sw * k) / 2.0 - ax * k
    oy = y0 + (h - sh * k) / 2.0 - ay * k
    return (lambda p: (ox + p[0] * k, oy + p[1] * k)), k


def _pt(pose, name, box):
    f, _ = _fitter(pose, box)
    return f(pose[name])


def figure(name, box, stroke=9, bb=None):
    """Return SVG for one posed figure inside `box` = (x, y, w, h).

    Pass `bb` (from union_bbox) to draw several poses at one shared scale."""
    pose = POSES[name]
    far = pose.get('far') or {}
    fit, k = _fitter_from(bb or _bbox(pose), box)
    ax, ay, bx, by = bb or _bbox(pose)
    fig_h = (by - ay) * k              # the figure's drawn height, in px
    out = []

    # far-side limbs first, so the near side reads on top
    if far:
        fp = dict(pose); fp.update(far)
        for a, b in LIMBS:
            if a in far or b in far:
                p, q = fit(fp[a]), fit(fp[b])
                out.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" '
                           'stroke-width="%.1f" stroke-linecap="round"/>'
                           % (p[0], p[1], q[0], q[1], FAR, stroke * 0.85))

    for a, b in LIMBS:
        p, q = fit(pose[a]), fit(pose[b])
        w = stroke * (1.25 if (a, b) == ('neck', 'hip') else 1.0)
        out.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" '
                   'stroke-width="%.1f" stroke-linecap="round"/>'
                   % (p[0], p[1], q[0], q[1], NAVY, w))

    hx, hy = fit(pose['head'])
    r = max(fig_h * 0.052, stroke * 1.35)   # head reads against the figure, not the line
    out.append('<circle cx="%.1f" cy="%.1f" r="%.1f" fill="%s"/>' % (hx, hy, r, NAVY))
    return '\n'.join(out)


